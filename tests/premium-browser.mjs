import { createRequire } from 'node:module';
import { spawn } from 'node:child_process';
import { existsSync, mkdirSync } from 'node:fs';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
mkdirSync('visual-proof/premium', { recursive: true });
const server = spawn(process.execPath, ['admin-control-center/server.mjs'], { cwd: new URL('..', import.meta.url), env: { ...process.env, PORT: '8138' }, stdio: 'pipe' });
await new Promise((resolve, reject) => { server.stdout.once('data', resolve); server.once('error', reject); server.once('exit', code => reject(new Error(`Admin test server exited (${code})`))); });
const browser = await chromium.launch({ executablePath: existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : undefined, headless: true, args: ['--no-sandbox'] });
let writes = [];
const statement = { id: '11111111-1111-4111-8111-111111111111', reference: 'AE-ST-TEST', restaurant_name: 'Test Restaurant', status: 'draft', final_payable_amount: 400, payout_hold: false, active_disputes: 0 };
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addInitScript(() => {
    sessionStorage.setItem('ae_control_center_token', 'test-only-session');
    sessionStorage.setItem('ae_control_center_user', JSON.stringify({ id: 1, username: 'test', role: 'admin' }));
  });
  await context.route('https://accounts.google.com/**', route => route.abort());
  await context.route('https://afghaneats-api.onrender.com/**', async route => {
    const method = route.request().method();
    if (method === 'OPTIONS') return route.fulfill({ status: 204, headers: { 'Access-Control-Allow-Origin': '*', 'Access-Control-Allow-Headers': '*', 'Access-Control-Allow-Methods': '*' } });
    const path = new URL(route.request().url()).pathname.split('/').at(-1);
    let data = {};
    if (path === 'auth.me') data = { id: 1, username: 'test', role: 'admin' };
    if (path === 'merchantFinance.adminOverview') data = { statements: [statement], restaurants: [], disputes: [] };
    if (path === 'merchantFinance.adminStatement') data = { statement, totals: { basePayable: 400, finalPayable: 400, adjustmentTotal: 0 }, orderLines: [], adjustments: [], disputes: [] };
    if (path === 'finance.adminOverview') data = { riders: [{ id: 'r1', full_name: 'Test Rider', cash_balance: 250 }], recentCash: [] };
    if (path === 'compensation.adminOverview') data = { compensations: [], settings: {} };
    if (path === 'foodSafety.adminCompleteness') data = { restaurants: [{ name: 'Test Restaurant', item_declared: 2, item_total: 4, option_declared: 0, option_total: 1 }] };
    if (path === 'ruleWorkers.snapshot') data = { enabled: true, findings: [], summary: {} };
    if (method === 'POST') { writes.push({ path, input: JSON.parse(route.request().postData()).json }); data = { success: true }; }
    return route.fulfill({ status: 200, contentType: 'application/json', headers: { 'Access-Control-Allow-Origin': '*' }, body: JSON.stringify({ result: { data: { json: data } } }) });
  });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:8138/#finance');
  await page.getByRole('heading', { name: 'Merchant statements', exact: true }).waitFor();
  assert.equal(writes.length, 0);
  await page.getByRole('button', { name: 'Rider cash', exact: true }).click();
  assert.equal(new URL(page.url()).hash, '#finance');
  await page.getByRole('button', { name: 'Review statement' }).click();
  const downloadReady = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download statement CSV' }).click();
  const download = await downloadReady;
  assert.ok(download.suggestedFilename().endsWith('.csv'));
  await page.getByRole('button', { name: 'Review approval', exact: true }).click();
  await page.locator('#confirm-dialog[open]').waitFor();
  assert.equal(writes.length, 0);
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal(writes.length, 0);
  await page.getByRole('button', { name: 'Review approval', exact: true }).click();
  await page.locator('#confirm-action').click();
  await page.waitForFunction(() => !document.querySelector('#confirm-dialog[open]'));
  await page.getByRole('heading', { name: 'Merchant statements', exact: true }).waitFor();
  assert.equal(writes.length, 1);
  assert.equal(writes[0].path, 'merchantFinance.adminApprove');
  const amount = page.locator('input[name="amount"]').first();
  await amount.fill('100');
  await page.evaluate(() => renderView(true));
  assert.equal(await amount.inputValue(), '100', 'background query must preserve a financial draft');
  await page.screenshot({ path: 'visual-proof/premium/admin-finance-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'visual-proof/premium/admin-finance-mobile.png', fullPage: true });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
  assert.equal(overflow, false, 'mobile viewport must not overflow horizontally');
  await page.getByRole('link', { name: 'Food safety', exact: false }).click();
  await page.getByRole('heading', { name: 'Declaration coverage' }).waitFor();
  assert.match(await page.locator('#view-root').innerText(), /2 \/ 4/);
  await page.evaluate(() => { state.user.role = 'restaurant_staff'; applyRoleNavigation(); setView('finance'); });
  assert.equal(await page.locator('[data-view="finance"]').isVisible(), false);
  assert.notEqual(await page.evaluate(() => state.view), 'finance');
  assert.deepEqual(errors, []);
  console.log('PASS: finance navigation, confirmation/cancel, exact API command, draft preservation, safety coverage, restricted role, desktop/mobile layout.');
} finally { await browser.close(); server.kill(); }
